def get_fence_language(preset_name: str) -> str | None:
    """
    获取预设对应的代码围栏语言标识。

    Returns:
        语言字符串（如 'python'）表示需要围栏；
        None 表示该预设不需要围栏（纯文本/文档类）。
    """
    if preset_name is None:
        return None
    return CODE_FENCE_MAP.get(preset_name.lower().strip())


def needs_code_fence(preset_name: str) -> bool:
    """判断该预设类型是否需要在组装时添加代码围栏"""
    return get_fence_language(preset_name) is not None


def wrap_with_fence(content: str, preset_name: str) -> str:
    """
    根据预设类型为内容包裹 markdown 代码围栏。

    - 代码/配置/数据类预设：包裹 ```language ... ```
    - 文本/文档类预设（markdown/plaintext/article/roleplay/dialogue/mixed）：原样返回
    - 已含围栏的内容：先剥离旧围栏再重新包裹，确保格式统一
    """
    if not content or not content.strip():
        return content

    fence_lang = get_fence_language(preset_name)
    if fence_lang is None:
        return content  # 文本类不需要围栏

    stripped = content.strip()

    # 如果内容已被代码围栏包裹，先剥离旧围栏，取内部内容
    if stripped.startswith('```') and stripped.endswith('```') and len(stripped) > 6:
        lines = stripped.split('\n')
        # 去掉首行（```language）和末行（```）
        if len(lines) >= 2:
            inner = '\n'.join(lines[1:-1])
            stripped = inner.strip()
            if not stripped:
                return content

    # 清理 AI 常见的违规前后缀
    lines = stripped.split('\n')

    # 去除前缀：空行 + 自然语言说明
    while lines:
        first = lines[0].strip()
        if not first:
            lines.pop(0)
            continue
        # 中文前缀
        if any(first.startswith(p) for p in (
            '以下是', '下面是', '代码如下', '代码：', '代码如下：',
            '以下是代码', '这是', '注意：', '说明：', '好的',
            '当然', '没问题', '这里', '下面', '好的，', '好的！',
            '没问题，', '没问题！', '当然，', '当然！',
        )):
            lines.pop(0)
            continue
        # 英文前缀
        if any(first.lower().startswith(p) for p in (
            'here is', 'here\'s', 'below is', 'the following',
            'sure', 'of course', 'certainly', 'yes,',
        )):
            lines.pop(0)
            continue
        break

    # 去除后缀：空行 + 总结性说明
    while lines:
        last = lines[-1].strip()
        if not last:
            lines.pop()
            continue
        # 中文后缀
        if any(last.startswith(p) for p in (
            '以上就是', '总结：', '说明：', '注意：',
            '希望这能', '如有问题', '如果需要',
            '请注意', '温馨提示',
        )):
            lines.pop()
            continue
        # 英文后缀
        if any(last.lower().startswith(p) for p in (
            'that\'s it', 'hope this helps', 'note:',
            'in summary', 'to summarize',
        )):
            lines.pop()
            continue
        break

    content = '\n'.join(lines)
    if not content.strip():
        return content

    return f'```{fence_lang}\n{content}\n```'
