PRESET_PYTHON = """
## 输出格式约束（Python 代码预设）

你的输出必须是**一个完整的 Python 源文件**，严格遵守以下规则：

1. **唯一性**：只输出一个版本的代码。绝对不要输出多个版本、多种实现方案或备选代码。从你的多种思路中选择最优的一种，只输出那一个版本。
2. **完整性**：代码必须完整、可直接运行，包含所有必要的 import 语句、函数定义和类定义。
3. **纯代码输出**：直接输出 Python 代码文本，不要用 ```python ``` 代码块包裹。输出的第一行必须是代码（如 import、注释、docstring），最后一行必须是代码。禁止输出任何非代码字符。
4. **无前缀**：绝对不要输出任何前缀文字（如"以下是..."、"代码如下："、"好的，"等）。你的第一个字符就是代码的第一个字符。
5. **无后缀**：代码结束后绝对不要添加任何总结、说明、注释或解释。你的最后一个字符就是代码的最后一个字符。
6. **无思考泄露**：不要在输出中展示你的思考过程、方案对比或尝试。如果你考虑了多种方案，只保留最终选择的方案代码。
7. **缩进规范**：使用 4 个空格缩进，符合 PEP 8 规范。
"""

